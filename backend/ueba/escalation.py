"""Escalation webhook - posts formatted alerts to ESCALATION_WEBHOOK_URL.

Supports ntfy.sh format and generic webhook endpoints.
"""
import os
from typing import Optional

import httpx

from ueba.credentials import get_secret
from ueba.logging_config import get_logger

logger = get_logger(__name__)


async def send_escalation(alert_data: dict) -> bool:
    """Send a formatted Markdown alert to the escalation webhook.

    Args:
        alert_data: Dict with alert fields including:
            - severity, classification, incident_summary
            - offending_host, recommended_containment
            - threat_matches, behavioral_flags
            - event data

    Returns:
        True if sent successfully, False otherwise.
    """
    webhook_url = get_secret("ESCALATION_WEBHOOK_URL")
    if not webhook_url:
        logger.warning("ESCALATION_WEBHOOK_URL not set, skipping escalation")
        return False

    severity = alert_data.get("severity", "unknown").upper()
    classification = alert_data.get("threat_classification", alert_data.get("classification", "unknown"))
    summary = alert_data.get("incident_summary", alert_data.get("summary", "No summary"))
    offending_host = alert_data.get("offending_host", alert_data.get("src_ip", "unknown"))
    containment = alert_data.get("recommended_containment", alert_data.get("containment", ""))
    confidence = alert_data.get("confidence", 0)

    # Build Markdown message
    sev_emoji = {"CRITICAL": "🔴", "HIGH": "🟠", "MEDIUM": "🟡", "LOW": "🔵", "INFO": "⚪"}.get(severity, "⚪")

    markdown = f"""# {sev_emoji} {severity} Alert: {classification}

**Offending Host:** `{offending_host}`
**Confidence:** {confidence}%

## Summary
{summary}

**Severity:** {severity}
**Classification:** {classification}
"""

    if containment:
        markdown += f"\n## Recommended Containment\n{containment}\n"

    # Include threat intel matches
    threat_matches = alert_data.get("threat_matches", [])
    if threat_matches:
        markdown += "\n## Threat Intelligence Matches\n"
        for tm in threat_matches[:5]:
            markdown += f"- **{tm.get('feed', 'unknown')}**: `{tm.get('ioc_value', '?')}` ({tm.get('threat_category', 'unknown')})\n"

    # Include behavioral flags
    behavioral_flags = alert_data.get("behavioral_flags", [])
    if behavioral_flags:
        markdown += "\n## Behavioral Flags\n"
        for bf in behavioral_flags[:5]:
            details = bf.get("details", {})
            markdown += f"- **{bf.get('flag_type', 'unknown')}**: {str(details)[:200]}\n"

    markdown += "\n---\n*Generated by UEBA Platform*"

    try:
        async with httpx.AsyncClient(timeout=30.0) as client:
            # Try ntfy.sh format first (uses Title header)
            headers = {
                "Content-Type": "text/markdown",
                "Title": f"[{severity}] {classification}",
                "Priority": "high" if severity in ("CRITICAL", "HIGH") else "default",
            }

            response = await client.post(webhook_url, content=markdown, headers=headers)

            if response.status_code >= 400:
                # Fallback: try JSON format
                logger.debug("Markdown POST failed, trying JSON", extra={
                    "extra_data": {"status": response.status_code}
                })
                json_response = await client.post(
                    webhook_url,
                    json={"text": markdown, "title": f"[{severity}] {classification}"},
                    headers={"Content-Type": "application/json"},
                )
                json_response.raise_for_status()

            logger.info("Escalation sent", extra={
                "extra_data": {
                    "severity": severity,
                    "classification": classification,
                    "offending_host": offending_host,
                }
            })
            return True

    except Exception as e:
        logger.error("Escalation webhook failed", extra={"extra_data": {"error": str(e)}})
        return False
